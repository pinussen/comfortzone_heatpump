#!/usr/bin/env python3
"""Validate the read schema and generate the static C++ table and reference.

Run with --check in CI. No third-party packages or live device are required.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TYPES = {'u8': (1, False), 'u16': (2, False), 'i16': (2, True), 'u32': (4, False)}


def validate(schema, status):
    if (schema['schema_version'], schema['protocol'], schema['prefix'], schema['byte_order']) != (
            1, 170, '010203040b08', 'little'):
        raise ValueError('Unsupported schema/profile/byte order')
    bindings = {name: typ for typ, name in re.findall(r'Subscribable<(\w+)>\s+(\w+)', status)}
    ids, names, occupied, used_bindings = set(), set(), set(), set()
    for f in schema['fields']:
        if not re.fullmatch(r'[a-z][a-z0-9_]*', f['id']) or f['id'] in ids:
            raise ValueError('Invalid/duplicate field id')
        if f['offline_name'] in names or f['binding'] in used_bindings:
            raise ValueError('Duplicate output name/binding')
        ids.add(f['id']); names.add(f['offline_name']); used_bindings.add(f['binding'])
        if f['binding'] not in bindings or bindings[f['binding']] not in ('byte','int16_t','uint16_t','uint32_t'):
            raise ValueError('Unknown/non-numeric C++ binding')
        if f['type'] not in TYPES or f['access'] != 'read':
            raise ValueError('Unsupported type/access')
        width, signed = TYPES[f['type']]
        if not re.fullmatch('[0-9a-f]{4}', f['address']) or type(f['bank']) is not int or f['bank'] not in (0,1,5):
            raise ValueError('Invalid bank/address')
        address = int(f['address'], 16)
        if address + width > 65536:
            raise ValueError('Field crosses address space')
        cells = {(f['bank'], a) for a in range(address, address+width)}
        if cells & occupied:
            raise ValueError('Overlapping register fields')
        occupied |= cells
        lo, hi = (-(1 << (8*width-1)), (1 << (8*width-1))-1) if signed else (0, (1 << (8*width))-1)
        lower, upper = f.get('raw_bounds', [lo, hi])
        if type(lower) is not int or type(upper) is not int or not lo <= lower <= upper <= hi:
            raise ValueError('Invalid raw bounds')
        if any(type(v) is not int or not lo <= v <= hi for v in f.get('invalid_raw', [])):
            raise ValueError('Invalid sentinel')
        if type(f['divisor']) is not int or f['divisor'] <= 0:
            raise ValueError('Invalid divisor')
        if f['evidence']['level'] not in ('inherited', 'capture', 'panel') or not f['evidence']['reference'] or not f['evidence']['note']:
            raise ValueError('Missing evidence')
    if not ids:
        raise ValueError('Empty schema')
    return bindings


def render(schema, status):
    bindings = validate(schema, status)
    header = ['// Generated by tools/generate_registers.py; edit registers_v170.json.',
              '#pragma once', '#include "comfortzone_status.h"',
              'namespace cz_registers {',
              'struct Field {',
              '    uint8_t bank, width;',
              '    uint16_t address;',
              '    bool is_signed;',
              '    int64_t minimum, maximum;',
              '    void (*publish)(COMFORTZONE_STATUS &, int64_t);',
              '};',
              'static const byte prefix_v170[] = {1,2,3,4,0x0b,8};',
              'static const Field fields_v170[] = {']
    doc = ['# Protocol 170 read registers', '',
           'Generated from `registers_v170.json`; do not edit this table manually.', '',
           'These are read mappings, not write authorization. `inherited` means the existing',
           'library interpretation still needs independent confirmation. Firmware keeps raw',
           'integer units and sentinels; presentation divides by the stated divisor.', '',
           '| Bank:address | Field | Type | Divisor | Unit | Raw bounds | Evidence |',
           '| --- | --- | --- | --- | --- | --- | --- |']
    for f in schema['fields']:
        width, signed = TYPES[f['type']]
        limits = (-(1 << (8*width-1)), (1 << (8*width-1))-1) if signed else (0, (1 << (8*width))-1)
        low, high = f.get('raw_bounds', limits)
        header.append(f'    {{{f["bank"]}, {width}, 0x{f["address"]}, {str(signed).lower()}, {low}LL, {high}LL, '
                      f'+[](COMFORTZONE_STATUS &s, int64_t v) {{ s.{f["binding"]} = static_cast<{bindings[f["binding"]]}>(v); }}}},')
        bounds = str(f['raw_bounds']) if 'raw_bounds' in f else 'type range'
        doc.append(f'| {f["bank"]:02x}:{f["address"]} | {f["id"]} | {f["type"]} | {f["divisor"]} | {f["unit"]} | {bounds} | {f["evidence"]["level"]} |')
    header += ['};', '}  // namespace cz_registers', '']
    doc += ['', 'Clock/calendar and derived flags are handled separately. No fragments are',
            'combined between replies. See the schema for evidence notes and sentinel values.', '']
    return {'comfortzone_registers_v170.h': '\n'.join(header), 'REGISTERS-170.md': '\n'.join(doc)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = render(json.loads((ROOT/'registers_v170.json').read_text()),
                     (ROOT/'comfortzone_status.h').read_text())
    for name, content in outputs.items():
        path = ROOT/name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated file: {name}; run tools/generate_registers.py')
        else:
            path.write_text(content)
    print('Protocol 170 schema and generated files verified')


if __name__ == '__main__':
    main()
